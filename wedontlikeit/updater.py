"""Signature updates from public feeds (default: MalwareBazaar by abuse.ch)."""

from __future__ import annotations

import io
import os
import re
import urllib.request
import zipfile
from pathlib import Path

from . import __version__

DEFAULT_URL = "https://bazaar.abuse.ch/export/txt/sha256/recent/"
MAX_DOWNLOAD = 256 << 20
HASH_RE = re.compile(rb"\b[a-fA-F0-9]{64}\b")


def download(url: str, auth_key: str | None = None, timeout: int = 60) -> bytes:
    headers = {"User-Agent": f"WeDontLikeIt/{__version__}"}
    if auth_key:
        headers["Auth-Key"] = auth_key  # abuse.ch may require a free key
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        raw = resp.read(MAX_DOWNLOAD + 1)
    if len(raw) > MAX_DOWNLOAD:
        raise ValueError("download too large")
    if raw[:2] == b"PK":  # full exports come zipped
        with zipfile.ZipFile(io.BytesIO(raw)) as zf:
            raw = b"\n".join(zf.read(n) for n in zf.namelist())
    return raw


def update(dest_dir: Path, url: str = DEFAULT_URL, auth_key: str | None = None,
           name: str = "MalwareBazaar.Sample", filename: str = "malwarebazaar.hashes") -> tuple[int, int]:
    """Downloads hashes and merges them into the local file. Returns (new, total)."""
    found = {h.decode().lower() for h in HASH_RE.findall(download(url, auth_key))}
    if not found:
        raise ValueError("no hashes in the response (does the feed need a key? try --key)")

    dest_dir = Path(dest_dir)
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / filename
    existing: set[str] = set()
    if dest.exists():
        for line in dest.read_text(encoding="utf-8").splitlines():
            tok = line.split("#", 1)[0].split()
            if tok:
                existing.add(tok[0].lower())

    new = found - existing
    if new:
        merged = sorted(existing | found)
        tmp = dest.with_suffix(".tmp")
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(f"# Generated by `wedontlikeit update` from {url}\n")
            f.writelines(f"{h} {name}\n" for h in merged)
        os.replace(tmp, dest)
    return len(new), len(existing | found)
